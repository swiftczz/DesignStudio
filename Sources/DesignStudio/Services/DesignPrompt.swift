import Foundation

/// 组装系统提示词与对话
nonisolated enum DesignPrompt {
    static func system(kind: ProjectKind, designSystem: DesignSystem?) -> String {
        var s = """
        You are DesignStudio, a world-class product designer and senior front-end engineer working inside an \
        infinite design canvas. A design is made of ARTBOARDS laid out side by side on the canvas — each artboard is \
        one screen (or one slide) and is a complete, self-contained HTML document rendered at a fixed size. The user \
        iterates with you through chat, by commenting on elements, and by editing element properties directly.

        ## Output contract (very important)
        1. Begin with a short explanation (1–3 sentences) of what you designed or changed. Always write this in the \
        same language the user writes in.
        2. Then output each artboard as its own fenced code block with this exact info string:
           ```html artboard="<artboard name>" width=<px> height=<px>
           <!DOCTYPE html>
           …complete document…
           ```
           - Every artboard is a COMPLETE HTML document designed for exactly that width × height. The <body> fills the \
           artboard edge to edge: no device frames, no outer centering, no letterboxing or scaling wrappers.
           - Name artboards in the user's language (e.g. "首页", "详情", "01 封面").
           - When modifying an existing design, output ONLY the artboards you changed or added, reusing the exact \
           existing artboard names; unchanged artboards are kept automatically. Always output the full document of \
           every artboard you output — never diffs or snippets.
        3. After the code blocks you may add up to 3 very short bullet suggestions for next iterations.
        4. If the request is genuinely ambiguous you may ask up to 2 clarifying questions instead of designing — but \
        prefer making sensible assumptions and designing.

        ## Element edits
        When the user's message has a "## 选中的元素" section, the user selected ONE element on the canvas and wants \
        to change only that element. Then, instead of artboards:
        - Write one short sentence about the change, then output exactly one fenced block with the info string \
        `element`:
          ```html element
          <the complete modified element: a single root element including every child you keep>
          ```
        - Keep the same tag and data-name unless asked otherwise. Leave everything outside this element untouched — \
        it is not in your output and will be kept as is.
        - Put visual changes in inline style attributes on the element or its children (you may reuse classes and \
        CSS variables that already exist in the artboard). Do not output <style>, <script>, <head>, or artboards.
        - Only if the request clearly cannot be done inside this element (e.g. it changes other parts of the screen \
        or adds screens), fall back to the normal artboard contract above.

        ## Technical rules
        - Each artboard is a single file: inline <style> and <script>. No build step, no frameworks that need compiling.
        - Keep the visual language consistent across artboards: repeat the same :root design tokens in each one.
        - Prefer real DOM content over content generated by JavaScript, so every element can be selected and edited \
        on the canvas. Give important elements a short data-name attribute in the user's language \
        (e.g. <section data-name="今日推荐">).
        - Allowed external resources: Google Fonts, https://cdn.tailwindcss.com, https://unpkg.com/lucide@latest \
        (icons), https://cdn.jsdelivr.net (small libraries such as Chart.js). Prefer inline SVG for icons and illustrations.
        - Never rely on external photos that may 404; use CSS gradients, SVG illustrations or https://picsum.photos \
        placeholders.
        - Define key design tokens as CSS custom properties on :root and use them everywhere.
        - Realistic, specific content (no lorem ipsum). Respect the user's language for all UI copy.
        - Accessible (semantic HTML, sufficient contrast, focus states), smooth micro-interactions.
        - Do not use alert(), confirm(), prompt(), or window.open().
        - Expose 3–6 meaningful "tweaks" so the user can adjust the design live, by embedding exactly this block \
        in the <head> of every artboard and making sure each variable is actually used in the CSS:
          <script type="application/json" id="ds-tweaks">
          [{"var":"--accent","label":"Accent color","type":"color","value":"#D97757"},
           {"var":"--radius","label":"Corner radius","type":"range","min":0,"max":32,"step":1,"unit":"px","value":12},
           {"var":"--font-scale","label":"Font scale","type":"range","min":0.8,"max":1.4,"step":0.05,"value":1},
           {"var":"--density","label":"Density","type":"select","options":["compact","comfortable"],"value":"comfortable"}]
          </script>
          Labels should be in the user's language. Supported types: color, range, select, text.

        ## Artifact type
        \(kind.guidance)
        """
        if let designSystem {
            s += "\n\n## Design system\n" + designSystem.promptDescription
        }
        return s
    }

    /// AI 修改时附带的画布选中上下文
    struct SelectionContext: Sendable {
        var artboardName: String
        var elementDescription: String?
        var elementHTML: String?
        /// 元素级修改：只让模型返回这个元素，由应用替换回画板
        var elementEdit = false
    }

    static func makeRequest(project: Project, designSystem: DesignSystem?,
                            newMessage: ChatMessage, profile: ProviderProfile,
                            pageID: UUID? = nil, selection: SelectionContext? = nil) -> LLMRequest {
        let limits = profile.limits
        let systemText = system(kind: project.kind, designSystem: designSystem)
        let page = project.workingDocument.page(pageID)
        let artboards = page?.artboards ?? []

        // 1. 本轮消息：附上当前页面所有画板 + 选中元素 + 批注
        var current = ""
        let elementEdit = selection?.elementEdit == true && !(selection?.elementHTML ?? "").isEmpty
        if elementEdit, let selection, let board = artboards.first(where: { $0.name == selection.artboardName }) {
            // 元素级修改：只附所在画板作为上下文，模型只返回修改后的元素
            current += "## 所在画板（仅供参考，请勿输出）\n画板「\(board.name)」的完整 HTML：\n\n"
            current += "```html artboard=\"\(board.name)\" width=\(Int(board.width)) height=\(Int(board.height))\n\(board.html)\n```\n\n"
            current += "## 选中的元素\n用户在画板「\(board.name)」中选中了 \(selection.elementDescription ?? "一个元素")。"
            current += "本轮只修改这个元素，下面是它当前的完整 HTML：\n"
            current += "```html\n\(selection.elementHTML ?? "")\n```\n\n"
        } else if !artboards.isEmpty {
            current += "## 当前设计\n画布上当前页面共有 \(artboards.count) 个画板，下面是它们的完整 HTML。请在此基础上修改，只输出改动或新增的画板（沿用原名称）：\n\n"
            for a in artboards {
                current += "```html artboard=\"\(a.name)\" width=\(Int(a.width)) height=\(Int(a.height))\n\(a.html)\n```\n\n"
            }
        }
        if let selection, !elementEdit {
            current += "## 用户在画布上选中的内容\n画板「\(selection.artboardName)」"
            if let d = selection.elementDescription { current += "中的 \(d)" }
            current += "。本轮修改请聚焦于它，除非用户另有说明，只输出这个画板。\n"
            if let h = selection.elementHTML, !h.isEmpty {
                let snippet = h.count > 3000 ? String(h.prefix(3000)) + "…" : h
                current += "```html\n\(snippet)\n```\n"
            }
            current += "\n"
        }
        if !newMessage.comments.isEmpty {
            current += "## 画布上的元素批注\n"
            for (i, c) in newMessage.comments.enumerated() {
                current += "\(i + 1). \(c.promptLine)\n"
            }
            current += "\n"
        }
        current += artboards.isEmpty ? "## 设计需求\n" : "## 本轮修改要求\n"
        current += newMessage.text
        // 放在消息末尾的格式提醒：对指令遵循较弱、或被其他末尾指令干扰的模型更稳
        if elementEdit {
            current += "\n\n（输出格式提醒：只输出一个 ```html element 代码块，内容是修改后的完整元素（单个根元素，包含保留的所有子元素），"
                + "样式改动写在内联 style 里；不要输出整个画板。）"
        } else {
            current += "\n\n（输出格式提醒：每个界面 / 每页幻灯片单独输出为一个 ```html artboard=\"名称\" width=宽 height=高 代码块，"
                + "不要把多个界面并排画在同一个画板里；修改时只输出改动或新增的画板，沿用原名称。）"
        }
        let latest = LLMMessage(role: .user, text: current, images: newMessage.attachments)

        // 2. 历史对话：旧的 HTML 用占位符替换（最新版本已附在本轮消息里）
        let past: [LLMMessage] = project.messages
            .filter { $0.errorText == nil && !($0.text.trimmed.isEmpty && $0.attachments.isEmpty) }
            .map { m in
                if m.role == .assistant {
                    let text = HTMLExtractor.conversationalText(m.text, placeholder: "\n[画板 HTML 已省略 —— 最新内容附在下方]\n")
                    return LLMMessage(role: .assistant, text: text.isEmpty ? "(已生成设计)" : text)
                }
                return LLMMessage(role: .user, text: userText(m))
            }

        // 3. 按模型的上下文上限尽量多带历史；上限未知时保留最近 16 条
        let history: [LLMMessage]
        if let context = limits.contextWindow {
            let reservedOutput = limits.maxOutput ?? min(32_000, context / 4)
            var budget = Int(Double(context) * 0.9) - reservedOutput
                - estimateTokens(systemText) - estimateTokens(latest)
            var kept: [LLMMessage] = []
            for m in past.reversed() {
                budget -= estimateTokens(m)
                if budget < 0 { break }
                kept.append(m)
            }
            history = kept.reversed()
        } else {
            history = Array(past.suffix(16))
        }

        return LLMRequest(
            system: systemText,
            messages: normalize(history + [latest]),
            // 输出用模型上限；未知时不传，由服务商按模型最大值处理
            maxTokens: limits.maxOutput,
            elementEdit: elementEdit
        )
    }

    /// 粗略估算 tokens：UTF-8 字节数 / 3（中文约 1 字 1 token，英文偏保守），图片按 1600 计
    static func estimateTokens(_ text: String) -> Int { text.utf8.count / 3 + 1 }

    static func estimateTokens(_ m: LLMMessage) -> Int { estimateTokens(m.text) + m.images.count * 1600 }

    private static func userText(_ m: ChatMessage) -> String {
        var text = m.text
        if let t = m.target { text = "（针对\(t.promptDescription)）" + text }
        guard !m.comments.isEmpty else { return text }
        return text + "\n（批注：" + m.comments.map(\.promptLine).joined(separator: "；") + "）"
    }

    /// 保证以 user 开头、角色交替（Anthropic API 要求）
    static func normalize(_ messages: [LLMMessage]) -> [LLMMessage] {
        var result: [LLMMessage] = []
        for m in messages {
            if result.isEmpty && m.role == .assistant { continue }
            if var last = result.last, last.role == m.role {
                last.text += "\n\n" + m.text
                last.images += m.images
                result[result.count - 1] = last
            } else {
                result.append(m)
            }
        }
        return result
    }

    static func summary(from text: String) -> String {
        let plain = HTMLExtractor.conversationalText(text)
        let line = plain.split(whereSeparator: \.isNewline).map { String($0).trimmed }.first { !$0.isEmpty } ?? "新版本"
        return line.count > 90 ? String(line.prefix(90)) + "…" : line
    }
}
